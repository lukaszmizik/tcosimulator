export function getPictogramGroups(language: SupportedLanguage) {
  const index = languageIndex[language]
  return reference.map(({ category, rows }) => ({
    id: category,
    title: titles[category][index],
    entries: rows.map(([code, ...labels], rowIndex) => ({
      id: `${category}-${rowIndex}`,
      label: labels[index],
      symbol: code.replace(/[\uE000-\uF8FF]/g, ' '),
      pictogram: category === 'countries' ? undefined : pictogramId(code),
    })),
  }))
}

function pictogramId(code: string) {
  if (!code) return 'glyph-data-transfer'
  return 'glyph-' + Array.from(code, character => character.charCodeAt(0).toString(16)).join('-')
}
